<?php

declare(strict_types=1);

namespace App\Mcp;

use App\Coaching\FillerTypeNotInSpeech;
use App\Coaching\PracticeExerciseGenerator;
use App\Processing\PermanentFailure;
use App\Report\ReportBuilder;
use Mcp\Capability\Attribute\McpTool;
use Mcp\Capability\Attribute\Schema;
use Mcp\Exception\ToolCallException;
use Mcp\Schema\ToolAnnotations;
use Psr\Log\LoggerInterface;

/**
 * The generate_practice_exercise MCP tool (SPEC §8): a thin wrapper over PracticeExerciseGenerator.
 *
 * The one tool that calls the AI, so the one tool that needs ANTHROPIC_API_KEY. Its failures
 * become readable tool errors; the provider's own message is only logged.
 */
final readonly class PracticeExerciseTool
{
    public function __construct(
        private McpSpeeches $speeches,
        private ReportBuilder $reportBuilder,
        private PracticeExerciseGenerator $generator,
        private LoggerInterface $logger,
    ) {
    }

    /**
     * @return array{speechId: string, title: string, focus: list<string>, instructions: string, prompts: list<string>, durationMinutes: int}
     */
    #[McpTool(
        name: 'generate_practice_exercise',
        title: 'Generate Practice Exercise',
        description: 'Writes a short speaking drill (a Practice Exercise) for one processed Speech, aimed at its most frequent Filler Type or at the Filler Type you name: a title, instructions, 3 speaking prompts and a duration. A Speech with no Fillers gets a general fluency exercise. Generated by AI each time and not saved; needs ANTHROPIC_API_KEY.',
        annotations: new ToolAnnotations(readOnlyHint: true, openWorldHint: true),
    )]
    public function generatePracticeExercise(
        #[Schema(description: 'The Speech ID (a UUID, as list_speeches gives it).', format: 'uuid')]
        string $speechId,
        #[Schema(description: 'The Filler Type to practise, e.g. "um" or "you know". Defaults to the Speech\'s most frequent one.')]
        ?string $focusFillerType = null,
    ): array {
        $speech = $this->speeches->done($speechId);
        $report = $this->reportBuilder->build($speech);

        try {
            $exercise = $this->generator->generate($report, $focusFillerType);
        } catch (FillerTypeNotInSpeech $e) {
            throw new ToolCallException($e->getMessage(), 0, $e);
        } catch (PermanentFailure $e) {
            $this->logFailure($speechId, $e);
            throw new ToolCallException('The AI service refused to write a Practice Exercise. Check that ANTHROPIC_API_KEY in .env.local is set and valid; the other Ah Counter tools work without it.', 0, $e);
        } catch (\Throwable $e) {
            $this->logFailure($speechId, $e);
            throw new ToolCallException('The AI service couldn\'t write a Practice Exercise right now. Try again in a moment.', 0, $e);
        }

        return [
            'speechId' => $speech->getId()->toRfc4122(),
            'title' => $exercise->title,
            'focus' => $exercise->focus,
            'instructions' => $exercise->instructions,
            'prompts' => $exercise->prompts,
            'durationMinutes' => $exercise->durationMinutes,
        ];
    }

    private function logFailure(string $speechId, \Throwable $e): void
    {
        $this->logger->error('generate_practice_exercise for Speech {speechId} failed: {error}', ['speechId' => $speechId, 'error' => $e->getMessage(), 'exception' => $e]);
    }
}
